"""Generate app rules and disjoint synthetic ML seed splits from the supplied list.

Only training phrases are bundled as matching references. Validation/test phrases
must never be added to the app references or used as training pairs.
"""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'tools/data/deed_catalog.json'


def load_catalog():
    source = json.loads(CATALOG.read_text(encoding='utf-8'))
    records = [dict(zip(source['fields'], row, strict=True)) for row in source['deeds']]
    if [r['number'] for r in records] != list(range(1, 51)):
        raise ValueError('Expected the original 50 deeds in document order.')
    for r in records:
        r['id'] = f"quran-{r['number']:02d}"
        if r['category_index'] not in range(7):
            raise ValueError('Invalid presentation category.')
        if any(not str(v).strip() for v in r.values()):
            raise ValueError('Empty catalog field.')
    return source, records


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check generated files without writing.')
    args = parser.parse_args()
    source, records = load_catalog()
    # JSON string literals are Dart-compatible after escaping interpolation.
    def quote(value):
        return json.dumps(value, ensure_ascii=False).replace('$', r'\$')

    lines = ["// Generated by tools/build_deed_catalog.py; edit the JSON source instead.",
             "part of '../main.dart';", '',
             f"const deedCatalogVersion = {quote(source['version'])};", '',
             'List<DeedTemplate> sourceDeedTemplates() => [']
    units = {3: 'BDT donated', 14: 'Meals', 16: 'BDT donated',
             19: 'Volunteer minutes', 42: 'Minutes'}
    for r in records:
        style = f"activityCategories[{r['category_index']}]"
        lines.extend(['  DeedTemplate(', f"    {quote(r['id'])},", f"    {quote(r['label'])},",
                      f'    {style}.category,', f"    {quote(r['description'])},",
                      f'    {style}.points,', f'    {style}.icon,', f'    {style}.tint,'])
        if r['number'] in units:
            lines.append(f"    unit: {quote(units[r['number']])},")
        lines.append('  ),')
    lines.extend(['];', '', 'List<MatchingRule> sourceDeedRules() => ['])
    splits = {'train': [], 'validation': [], 'test': []}
    # These source deeds intentionally overlap. Runtime still selects one.
    equivalent = {22: [22, 48], 48: [22, 48], 8: [8, 50], 50: [8, 50]}
    for r in records:
        examples = [r['english_example'], r['bengali_example'], r['banglish_example']]
        lines.extend(['  MatchingRule(', f"    {quote(r['id'])},", f"    {quote(r['label'])},",
                      f"    {quote(r['description'])},",
                      '    [' + ', '.join(quote(e) for e in examples) + '],',
                      f"    templates[{r['number'] - 1}],",
                      # Existing app category points; the source specifies no point values.
                      f"    templates[{r['number'] - 1}].points,",
                      f"    sourceNote: {quote(r['reference'])},", '  ),'])
        for lang, text in zip(('en', 'bn', 'banglish'), examples):
            splits['train'].append({'text': text, 'rule_ids': [r['id']], 'language': lang})
        ids = [f'quran-{n:02d}' for n in equivalent.get(r['number'], [r['number']])]
        splits['validation'].append({'text': r['validation_example'], 'rule_ids': ids, 'language': 'en'})
        splits['test'].append({'text': r['test_example'], 'rule_ids': ids,
                               'language': 'banglish' if r['number'] in (2, 5) else 'bn'})
    multilingual = json.loads((ROOT / 'tools/data/multilingual_validation.json').read_text(encoding='utf-8'))
    for r, (language, text) in zip(records, multilingual['examples_in_catalog_order'], strict=True):
        ids = [f'quran-{n:02d}' for n in equivalent.get(r['number'], [r['number']])]
        splits['validation'].append({'text': text, 'rule_ids': ids, 'language': language})
    # Source-label review contrasts cover all deeds, without using holdout text.
    for r in records:
        action = r['label'].removesuffix('.')
        action = action[0].lower() + action[1:]
        for text in (f'I did not do this: {action}.',
                     f'I intend to {action} tomorrow.',
                     f'How should I {action}?'):
            splits['train'].append({'text': text, 'rule_ids': [], 'language': 'en'})
    # Separately authored Banglish holdout: never bundled or used for fitting.
    banglish = json.loads((ROOT / 'tools/data/banglish_test.json').read_text(encoding='utf-8'))
    if len(banglish['positive_examples_in_catalog_order']) != len(records):
        raise ValueError('Banglish holdout must cover all 50 deeds in source order.')
    for record, text in zip(records, banglish['positive_examples_in_catalog_order'], strict=True):
        ids = [f'quran-{n:02d}' for n in equivalent.get(record['number'], [record['number']])]
        splits['test'].append({'text': text, 'rule_ids': ids, 'language': 'banglish'})
    splits['test'].extend({'text': text, 'rule_ids': [], 'language': 'banglish'}
                          for text in banglish['review_examples'])
    # Negative examples are explicit review cases, never an extra deed class.
    review = {
        'train': [
            ('en', 'I did not help my friend with the problem.'),
            ('en', 'I will donate money next week.'),
            ('en', 'I shouted at my parents and refused to help them.'),
            ('en', 'My friend gave food to a hungry person, but I did nothing.'),
            ('bn', 'আমি কাউকে সাহায্য করিনি।'),
            ('bn', 'আগামীকাল গরিবদের খাবার দেওয়ার ইচ্ছা আছে।'),
            ('bn', 'আমি ক্রেতাকে ওজনে কম দিয়েছি।'),
            ('banglish', 'ami aj namaz porini'),
            ('banglish', 'ami pore dan korbo ekhono korini'),
            ('en', 'The weather forecast predicts rain tonight.'),
            ('bn', 'আজ আমার ফোনের চার্জ শেষ।'),
            ('banglish', 'amar laptop er rong kalo'),
        ],
        'validation': [
            ('en', 'I never donated anything to that charity.'),
            ('en', 'Tomorrow I intend to visit my sick mother.'),
            ('en', 'How can I pay zakat?'),
            ('en', 'If I had time I would volunteer.'),
            ('en', 'My sister performed all her prayers today.'),
            ('en', 'I cheated the customer by giving less weight.'),
            ('en', 'I bought a new blue phone case.'),
            ('bn', 'আজ নামাজ পড়া হয়নি।'),
            ('bn', 'ইচ্ছা ছিল কিন্তু রোজা রাখিনি।'),
            ('banglish', 'kal goribder taka dibo'),
            ('banglish', 'ami bondhuke help kori nai'),
            ('en', 'qwerty asdf zxcv'),
        ],
        'test': [
            ('bn', 'আমি ক্ষুধার্ত মানুষটিকে খাবার দিইনি।'),
            ('bn', 'পরের মাসে যাকাত দেওয়ার পরিকল্পনা করেছি।'),
            ('bn', 'কীভাবে প্রতিবেশীকে সাহায্য করব?'),
            ('bn', 'আমার ভাই আজ রক্ত দিয়ে একজনকে বাঁচিয়েছে।'),
            ('bn', 'আমি বন্ধুর কাছে মিথ্যা বলেছি।'),
            ('bn', 'গতকাল ক্রিকেট ম্যাচ দেখলাম।'),
            ('banglish', 'ami goribke kono taka dei nai'),
            ('banglish', 'shomoy pele etimder help kortam'),
            ('banglish', 'amar bon aj roja rekheche ami rakhini'),
            ('en', 'I spread a cruel rumour about my colleague.'),
            ('en', 'I forgot my promise and broke our agreement.'),
            ('en', 'My bus ticket is in my pocket.'),
        ],
    }
    lines.append('];')
    outputs = {ROOT / 'lib/src/deed_catalog.g.dart': '\n'.join(lines) + '\n'}
    seen = set()
    for split, rows in splits.items():
        rows.extend({'text': text, 'rule_ids': [], 'language': lang} for lang, text in review[split])
        for row in rows:
            key = row['text'].strip().casefold()
            if key in seen:
                raise ValueError('Text leakage or duplicate between splits: ' + key)
            seen.add(key)
        outputs[ROOT / f'tools/data/{split}.jsonl'] = ''.join(
            json.dumps(row, ensure_ascii=False) + '\n' for row in rows)
    for path, text in outputs.items():
        if args.check:
            if not path.exists() or path.read_text(encoding='utf-8') != text:
                raise SystemExit(f'Generated file differs: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding='utf-8')
    print(f"50 source deeds; split sizes: { {k: len(v) for k, v in splits.items()} }. Synthetic, unreviewed seed examples.")


if __name__ == '__main__':
    main()
